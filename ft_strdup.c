#include "libft.h"

/*
** Returns a newly allocated copy of s (len + 1 for the '\0').
** Returns NULL if malloc fails. The result must be freed by the caller.
*/

char	*ft_strdup(const char *s)
{
	char	*dup;
	size_t	len;

	len = ft_strlen(s);
	dup = malloc(len + 1);
	if (!dup)
		return (NULL);
	ft_memcpy(dup, s, len + 1);
	return (dup);
}
