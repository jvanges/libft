#include "libft.h"

/*
** Copies n bytes from src to dst. The areas must not overlap
** (use ft_memmove otherwise).
** If dst and src are both NULL, returns NULL: this guards against
** calls like ft_memcpy(NULL, NULL, 3) that some testers check.
** Bytes are compared/written through unsigned char*, as required by
** the void* semantics. Returns dst.
*/

void	*ft_memcpy(void *dst, const void *src, size_t n)
{
	size_t			i;
	unsigned char	*d;
	unsigned char	*s;

	if (!dst && !src)
		return (NULL);
	d = (unsigned char *)dst;
	s = (unsigned char *)src;
	i = 0;
	while (i < n)
	{
		d[i] = s[i];
		i++;
	}
	return (dst);
}
