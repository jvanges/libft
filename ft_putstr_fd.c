#include "libft.h"

/*
** Writes the string s to fd in a single write() call.
** Does nothing if s is NULL.
*/

void	ft_putstr_fd(char *s, int fd)
{
	if (!s)
		return ;
	write(fd, s, ft_strlen(s));
}
