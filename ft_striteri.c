#include "libft.h"

/*
** Applies f to each character of s, passing its index and the address
** of the character so that f can modify the string in place
** (unlike ft_strmapi, nothing is allocated). No-op if s or f is NULL.
*/

void	ft_striteri(char *s, void (*f)(unsigned int, char *))
{
	unsigned int	i;

	if (!s || !f)
		return ;
	i = 0;
	while (s[i])
	{
		f(i, s + i);
		i++;
	}
}
